  function readCookie() {
    const m = /(?:^|;\s*)exe-lang=(ja|en)/.exec(document.cookie);
    return m ? m[1] : null;
  }
  let lang = readCookie() || ((navigator.language || "").toLowerCase().startsWith("ja") ? "ja" : "en");

  function t(key, vars) {
    let s = (DICT[lang] && DICT[lang][key]) || DICT.ja[key] || key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
    return s;
  }

  function apply(root) {
    document.documentElement.lang = lang;
    for (const el of (root || document).querySelectorAll("[data-i18n]")) el.textContent = t(el.dataset.i18n);
  }

  function setLang(next) {
    lang = next;
    document.cookie = "exe-lang=" + next + "; path=/; max-age=31536000; samesite=lax";
  }

  window.I18N = { t, apply, setLang, get lang() { return lang; } };
